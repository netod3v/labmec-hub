const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
  const source=fs.readFileSync(path.resolve(__dirname,'../../assets/note-whiteboard-model.js'),'utf8');
  const model=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
  const defaults=model.defaultWhiteboardSettings();
  assert.equal(defaults.recognize,true);assert.equal(defaults.wheel,'zoom');
  assert.deepEqual(defaults.recognizeTypes,['ellipse','rect','triangle','line']);
  const invalid=model.normalizeWhiteboardSettings({color:'javascript:alert(1)',wheel:'invalid',hiddenTools:['pen','missing'],shortcuts:{pen:'Ctrl+c'},pens:{pen:{width:Infinity}}});
  assert.equal(invalid.color,'#ffffff');assert.equal(invalid.wheel,'zoom');assert.deepEqual(invalid.hiddenTools,['pen']);assert.equal(invalid.shortcuts.pen,'p');assert.equal(invalid.pens.pen.width,4);
  const custom=model.normalizeWhiteboardSettings({...defaults,shortcuts:{...defaults.shortcuts,pen:'q'}});assert.equal(custom.shortcuts.pen,'q');
  assert.equal(model.whiteboardKey({key:' ',ctrlKey:false,altKey:false,shiftKey:false}),'Space');
  assert.equal(model.whiteboardKey({key:'z',metaKey:true,shiftKey:true}),'Ctrl+Shift+z');
  const stroke=points=>({id:'test',type:'stroke',points,color:'#111827',width:4});
  assert.equal(model.recognizedInk(stroke([{x:0,y:0},{x:50,y:1},{x:100,y:0}]),['line']).type,'line');
  assert.equal(model.recognizedInk(stroke([{x:0,y:0},{x:50,y:30},{x:100,y:0}]),['line']),null);
  const interpolate=vertices=>vertices.flatMap((v,i)=>i?Array.from({length:10},(_,j)=>({x:vertices[i-1].x+(v.x-vertices[i-1].x)*(j+1)/10,y:vertices[i-1].y+(v.y-vertices[i-1].y)*(j+1)/10})):[v]);
  const rect=interpolate([{x:10,y:10},{x:110,y:10},{x:110,y:90},{x:10,y:90},{x:10,y:10}]);
  assert.equal(model.recognizedInk(stroke(rect),defaults.recognizeTypes).type,'rect');
  const triangle=interpolate([{x:60,y:10},{x:110,y:90},{x:10,y:90},{x:60,y:10}]);
  assert.equal(model.recognizedInk(stroke(triangle),defaults.recognizeTypes).type,'triangle');
  const circle=Array.from({length:65},(_,i)=>({x:100+50*Math.cos(i*Math.PI/32),y:100+50*Math.sin(i*Math.PI/32)}));
  assert.equal(model.recognizedInk(stroke(circle),defaults.recognizeTypes).type,'ellipse');
  assert.equal(model.recognizedInk(stroke(circle),['line']),null);
  assert.equal(model.pointInLasso({x:40,y:40},[{x:0,y:0},{x:80,y:0},{x:80,y:80},{x:0,y:80}]),true);
  assert.equal(model.pointInLasso({x:90,y:40},[{x:0,y:0},{x:80,y:0},{x:80,y:80},{x:0,y:80}]),false);
  const objects=[stroke([{x:10,y:10},{x:20,y:20}]),{id:'img',type:'bitmap',x1:20,y1:20,x2:40,y2:40}];
  const resized=model.resizeWhiteboardObjects(objects,{x1:10,y1:10,x2:40,y2:40},{x1:0,y1:0,x2:60,y2:60});
  assert.deepEqual(resized[0].points,[{x:0,y:0},{x:20,y:20}]);assert.equal(resized[1].x2,60);assert.equal(objects[1].x2,40);
  console.log('PASS: settings defaults/validation, fixed shortcut protection, four shape recognizers, lasso geometry and object resizing');
})().catch(error=>{console.error(error);process.exitCode=1;});

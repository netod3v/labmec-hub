const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context=vm.createContext({});
for(const path of ['assets/activity-notifications.js','assets/notification-state.js'])vm.runInContext(fs.readFileSync(path,'utf8').replace(/export function /g,'function '),context);
const posts=[{id:'p',uid:'alice',comments:{c:{uid:'bob',ts:10,replies:{r:{uid:'carol',ts:11}}},mine:{uid:'alice',ts:12}}}];
let items=context.activityNotifications(posts,[], 'alice',{});
assert.equal(items.length,2);assert.equal(items[0].kind,'post-comment');assert.equal(items[1].kind,'post-reply');
assert.notEqual(context.notificationKey(items[0]),context.notificationKey(items[1]));
assert.equal(context.activityNotifications(posts,[],'bob',{}).length,1);
assert.equal(context.activityNotifications(posts,[],'outsider',{}).length,0);
items=context.activityNotifications([],[{id:'d',uid:'bob',ts:20,assignedTo:{alice:true}}],'alice',{});
assert.equal(items.length,1);assert.equal(items[0].kind,'demand-assigned');
const first={kind:'achievement',notificationId:'achievement-first-post',ts:30};
assert.equal(context.notificationKey(first),context.notificationKey({...first,title:'Updated'}));
assert.notEqual(context.notificationKey(first),context.notificationKey({...first,notificationId:'achievement-five-posts'}));
const records={[context.notificationKey(first)]:{read:true}};
assert.equal(context.notificationPage([first],records,1).unread,0);
records[context.notificationKey(first)].deleted=true;
assert.equal(context.notificationPage([first],records,1).total,0);
console.log('Activity notifications: comments, replies, assignments, unique achievements, read/delete passed.');
